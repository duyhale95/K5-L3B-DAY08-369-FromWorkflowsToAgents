"""Bonus B7 — metamorphic audit of the three candidate grader `summarize` variants.

The instructor ships `src/grader_audit/grader_{a,b,c}.py`; we never edit them.
This module runs the three official metamorphic relations from
`src/grader_audit/README.md` plus one relation of our own (trial-order
invariance) against every variant, and records exact numeric evidence.

Run from `src/` to regenerate the deterministic JSON evidence:

    python -m bonus.grader_audit --out reports/bonus_grader_audit.json

Nothing here reads a clock, a random source, or a network. The same input list
always produces the same report, so the JSON can be regenerated byte-for-byte.
"""

from __future__ import annotations

import argparse
import importlib
import json
from pathlib import Path
from typing import Any, Callable

from lab8.compensation import quote
from lab8.metrics import summarize as _base_summarize

FIXTURES = Path(__file__).resolve().parents[1] / "grader_audit" / "fixtures"
GRADERS = ("grader_a", "grader_b", "grader_c")
SCOPE = GRADERS + ("order_sensitive_mutant",)
TOL = 1e-9

RELATIONS = (
    "claim_delay_2_vs_3",
    "infra_errors_do_not_move_pass_rate",
    "duplicated_list_keeps_rates_doubles_totals",
    "trial_order_does_not_move_metrics",
)


def load_fixture(name: str) -> dict[str, Any]:
    return json.loads((FIXTURES / f"{name}.json").read_text(encoding="utf-8"))


def _trial(
    claim_id: str,
    seed: int,
    *,
    passed: bool,
    cost_estimate: float = 10.0,
    steps: int = 3,
    reason: str | None = None,
) -> dict[str, Any]:
    """One trial row in the shape `lab8.metrics.summarize` reads."""
    return {
        "shape": "workflow",
        "claim_id": claim_id,
        "seed": seed,
        "passed": passed,
        "cost_estimate": cost_estimate,
        "steps": steps,
        "model_calls": 2,
        "tool_calls": 5,
        "reason": reason or ("ok" if passed else "refund_mismatch"),
        "infra_error": False,
    }


def order_sensitive_mutant(trials: list[dict[str, Any]]) -> dict[str, Any]:
    """A deliberately defective grader that only trial order can expose.

    It handles infrastructure errors the right way (like grader_b) but adds the
    cost of every even-position trial to the shape total. Because the duplicate
    fixture repeats an even-length list, the added amount doubles with the list,
    so all three official relations still pass. Reversing the same list moves
    different trials into even positions, so the total changes.
    """
    rows = [dict(t, passed=None) if t.get("infra_error") else dict(t) for t in trials]
    report = _base_summarize(rows)
    for shape, stats in report.items():
        if not stats.get("graded_trials"):
            continue
        extra = sum(
            float(row["cost_estimate"])
            for index, row in enumerate(rows)
            if row["shape"] == shape and index % 2 == 0 and row["passed"] is not None
        )
        stats["total_simulated_cost_vnd"] += extra
        if stats["successes"]:
            stats["cost_per_success_vnd"] = stats["total_simulated_cost_vnd"] / stats["successes"]
    return report


def summarizer(name: str) -> Callable[[list[dict[str, Any]]], dict[str, Any]]:
    if name == "order_sensitive_mutant":
        return order_sensitive_mutant
    if name not in GRADERS:
        raise ValueError(f"unknown candidate grader: {name}")
    return importlib.import_module(f"grader_audit.{name}").summarize


def _close(left: Any, right: Any) -> bool:
    if left is None or right is None:
        return left is right
    return abs(float(left) - float(right)) <= TOL * max(1.0, abs(float(left)), abs(float(right)))


def _same_rates(
    left: dict[str, Any],
    right: dict[str, Any],
    keys: tuple[str, ...] = ("pass_rate", "pass_5", "seed_variance"),
) -> list[str]:
    changed = []
    for key in keys:
        if not _close(left.get(key), right.get(key)):
            changed.append(f"{key}:{left.get(key)}!={right.get(key)}")
    left_seeds = left.get("seed_pass_rates") or {}
    right_seeds = right.get("seed_pass_rates") or {}
    if set(left_seeds) != set(right_seeds):
        changed.append(f"seed_pass_rates:keys {sorted(left_seeds)}!={sorted(right_seeds)}")
    else:
        for seed in sorted(left_seeds):
            if not _close(left_seeds[seed], right_seeds[seed]):
                changed.append(f"seed_pass_rates[{seed}]:{left_seeds[seed]}!={right_seeds[seed]}")
    return changed


def _outcome(relation: str, violations: list[str], evidence: dict[str, Any]) -> dict[str, Any]:
    return {
        "relation": relation,
        "passed": not violations,
        "violations": violations,
        "evidence": evidence,
    }


def relation_claim_delay(name: str) -> dict[str, Any]:
    """delay_days 2 (below min_delay_days 3) denies; 3 pays the shipping fee only.

    Per `grader_audit/README.md` this fixture checks the business decision, not
    `summarize`. We also feed the two decisions to the candidate grader and check
    that it reports one success out of two graded trials.
    """
    fixture = load_fixture("metamorphic_claim_delay")
    amounts = {
        side: int(quote(fixture[side]["order"], fixture["policies"], as_of=fixture["as_of"]).amount_vnd)
        for side in ("a", "b")
    }
    expected_b = int(fixture["b"]["order"]["shipping_fee_vnd"])
    trials = [
        _trial(fixture["a"]["claim"]["claim_id"], 11, passed=amounts["a"] > 0, reason="no_entitlement"),
        _trial(fixture["b"]["claim"]["claim_id"], 11, passed=amounts["b"] > 0),
    ]
    stats = summarizer(name)(trials)["workflow"]
    violations: list[str] = []
    if amounts["a"] != 0:
        violations.append(f"delay_2_quote:{amounts['a']}!=0")
    if amounts["b"] != expected_b:
        violations.append(f"delay_3_quote:{amounts['b']}!={expected_b}")
    if int(stats["graded_trials"]) != 2:
        violations.append(f"graded_trials:{stats['graded_trials']}!=2")
    if int(stats["successes"]) != 1:
        violations.append(f"successes:{stats['successes']}!=1")
    if not _close(stats["pass_rate"], 0.5):
        violations.append(f"pass_rate:{stats['pass_rate']}!=0.5")
    evidence = {
        "quote_a_vnd": amounts["a"],
        "quote_b_vnd": amounts["b"],
        "stats": {key: stats[key] for key in ("graded_trials", "successes", "pass_rate")},
    }
    return _outcome(RELATIONS[0], violations, evidence)


def relation_infra(name: str) -> dict[str, Any]:
    """`b` = `a` plus infra_error trials. Graded pass metrics must not move."""
    fixture = load_fixture("metamorphic_infra")
    calculate = summarizer(name)
    a = calculate(fixture["a"])["workflow"]
    b = calculate(fixture["b"])["workflow"]
    violations: list[str] = []
    if int(a["graded_trials"]) != int(b["graded_trials"]):
        violations.append(f"graded_trials:{a['graded_trials']}!={b['graded_trials']} (infra trials graded as shape decisions)")
    if int(a["successes"]) != int(b["successes"]):
        violations.append(f"successes:{a['successes']}!={b['successes']}")
    for change in _same_rates(a, b):
        violations.append(f"rate_changed:{change}")
    evidence = {
        "infra_trials_added": len(fixture["b"]) - len(fixture["a"]),
        "a": {key: a[key] for key in ("trials", "graded_trials", "successes", "pass_rate", "pass_5")},
        "b": {key: b[key] for key in ("trials", "graded_trials", "successes", "pass_rate", "pass_5")},
    }
    return _outcome(RELATIONS[1], violations, evidence)


def relation_duplicate(name: str) -> dict[str, Any]:
    """`b` = `a` + `a`. Rates stay equal; counts and total cost double.

    `pass_5` is recorded but kept out of the verdict. `metrics.summarize` counts a
    claim for pass^5 only when it has exactly `len(seeds)` graded rows; `b` has
    four rows per claim over two seeds, so every candidate drops from 0.667 to 0.0.
    That is an inherited limitation of the reference ruler, identical in all three
    candidates, and is reported explicitly in the evidence instead of being blamed
    on one candidate.
    """
    fixture = load_fixture("metamorphic_duplicate")
    calculate = summarizer(name)
    a = calculate(fixture["a"])["workflow"]
    b = calculate(fixture["b"])["workflow"]
    violations = [
        f"rate_changed:{change}" for change in _same_rates(a, b, keys=("pass_rate", "seed_variance"))
    ]
    for key in ("mean_steps", "p95_steps", "mean_model_calls", "mean_tool_calls", "cost_per_success_vnd"):
        if not _close(a.get(key), b.get(key)):
            violations.append(f"rate_changed:{key}:{a.get(key)}!={b.get(key)}")
    for key in ("trials", "graded_trials", "successes", "total_simulated_cost_vnd"):
        doubled = 2 * float(a[key])
        if not _close(b[key], doubled):
            violations.append(f"totals_not_doubled:{key}:{b[key]}!=2*{a[key]}={doubled}")
    evidence = {
        "a": {key: a[key] for key in ("trials", "graded_trials", "successes", "total_simulated_cost_vnd", "cost_per_success_vnd")},
        "b": {key: b[key] for key in ("trials", "graded_trials", "successes", "total_simulated_cost_vnd", "cost_per_success_vnd")},
        "expected_total_simulated_cost_vnd": 2 * float(a["total_simulated_cost_vnd"]),
        "pass_5": {"a": a["pass_5"], "b": b["pass_5"]},
        "pass_5_inherited_limitation": (
            "metrics.summarize counts pass^5 only when a claim has exactly len(seeds) graded rows; "
            "the duplicated list has 4 rows per claim over 2 seeds, so pass_5 becomes 0 for every candidate. "
            "All three candidates share this behaviour; it is not evidence for or against one of them."
        ),
    }
    return _outcome(RELATIONS[2], violations, evidence)


def relation_order(name: str) -> dict[str, Any]:
    """Reversing the same trial list must not move any aggregate metric.

    This is the newly designed relation. The official duplicate relation only
    appends a copy, so a grader that keys a cost contribution on "the first row
    I saw for a claim" (or on row position) can go unnoticed: order never
    changes. Reversing the identical multiset of trials changes only order.
    """
    fixture = load_fixture("metamorphic_duplicate")
    ordered = fixture["a"]
    reversed_rows = list(reversed(ordered))
    calculate = summarizer(name)
    a = calculate(ordered)["workflow"]
    b = calculate(reversed_rows)["workflow"]
    violations: list[str] = []
    for key in (
        "trials",
        "graded_trials",
        "successes",
        "pass_rate",
        "pass_5",
        "seed_variance",
        "total_simulated_cost_vnd",
        "cost_per_success_vnd",
        "mean_steps",
        "p95_steps",
        "mean_model_calls",
        "mean_tool_calls",
    ):
        if not _close(a.get(key), b.get(key)):
            violations.append(f"metric_changed:{key}:{a.get(key)}!={b.get(key)}")
    for change in _same_rates(a, b):
        if not any(change.split(":", 1)[0] in item for item in violations):
            violations.append(f"metric_changed:{change}")
    evidence = {
        "a": {key: a[key] for key in ("trials", "graded_trials", "successes", "total_simulated_cost_vnd", "cost_per_success_vnd")},
        "reversed": {key: b[key] for key in ("trials", "graded_trials", "successes", "total_simulated_cost_vnd", "cost_per_success_vnd")},
        "note": "same multiset of trials, only the order differs",
    }
    return _outcome(RELATIONS[3], violations, evidence)


def audit_grader(name: str) -> dict[str, Any]:
    relations = {
        RELATIONS[0]: relation_claim_delay(name),
        RELATIONS[1]: relation_infra(name),
        RELATIONS[2]: relation_duplicate(name),
        RELATIONS[3]: relation_order(name),
    }
    return {
        "grader": name,
        "relations": relations,
        "passes_all_relations": all(item["passed"] for item in relations.values()),
        "failed_relations": [key for key, item in relations.items() if not item["passed"]],
    }


def audit_all() -> dict[str, Any]:
    graders = {name: audit_grader(name) for name in GRADERS}
    mutant = audit_grader("order_sensitive_mutant")
    return {
        "relations": list(RELATIONS),
        "graders": graders,
        "correct_graders": [name for name, report in graders.items() if report["passes_all_relations"]],
        "mutant_control": mutant,
        "claim": (
            "grader_b is the only candidate whose rates and totals survive all three official "
            "relations; the new trial-order relation additionally catches a position-dependent "
            "accumulator that the official three do not."
        ),
        "generated_by": "python -m bonus.grader_audit",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate the Bonus B7 grader-audit evidence")
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    report = audit_all()
    path = Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")
    print(f"correct_graders {report['correct_graders']}")
    for name, item in report["graders"].items():
        failed = ", ".join(item["failed_relations"]) or "none"
        print(f"{name}: failed relations = {failed}")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
